  function createElement(tag, className, text) {
    var element = document.createElement(tag);
    if (className) element.className = className;
    if (text !== undefined) element.textContent = text;
    return element;
  }

  function renderList(tag, items) {
    var list = createElement(tag, 'terms-list');
    items.forEach(function (item) {
      var li = createElement('li', '', Array.isArray(item) ? item[0] : item);
      if (Array.isArray(item)) li.appendChild(renderList('ul', item[1]));
      list.appendChild(li);
    });
    return list;
  }

  function renderBlock(block) {
    var kind = block[0];
    if (kind === 'h') return createElement('h4', 'terms-heading', block[1]);
    if (kind === 'p') return createElement('p', 'terms-text', block[1]);
    if (kind === 'ol' || kind === 'ul') return renderList(kind, block[1]);
    var lead = createElement('div', 'terms-lead');
    block[1].forEach(function (child) { lead.appendChild(renderBlock(child)); });
    return lead;
  }

  /** container に規約とポリシーの全文を書く（中身を置き換える）。 */
  function renderTermsDocument(container) {
    container.textContent = '';
    TERMS_PARTS.forEach(function (part) {
      var article = createElement('article', 'terms');
      article.appendChild(createElement('h3', 'terms-title', part.title));
      part.blocks.forEach(function (block) { article.appendChild(renderBlock(block)); });
      article.appendChild(createElement('p', 'terms-version', '附則：第' + TERMS_VERSION + '版（' + TERMS_EFFECTIVE + 'から適用）'));
      container.appendChild(article);
    });
  }

  VIEW.TERMS_VERSION = TERMS_VERSION;
  VIEW.renderTermsDocument = renderTermsDocument;
